def cross4_hist_ast_assignment_contract(source_text):
    """Check the actual ``self.modified.Rm['integrals']`` AST alias once."""
    result = {
        "source_present": isinstance(source_text, str) and bool(source_text),
        "AST_parsed": False,
        "incoming_integrals_assignment_count": 0,
        "actual_alias": "self.modified.Rm['integrals']",
        "passed": False,
    }
    if not isinstance(source_text, str) or not source_text:
        return result
    try:
        tree = cross4_hist_ast.parse(source_text, filename="patch.py")
    except (SyntaxError, TypeError, ValueError):
        return result
    result["AST_parsed"] = True
    for node in cross4_hist_ast.walk(tree):
        if not isinstance(node, cross4_hist_ast.Assign):
            continue
        value = node.value
        if not (isinstance(value, cross4_hist_ast.Subscript)
                and isinstance(value.value, cross4_hist_ast.Attribute)
                and value.value.attr == "Rm"
                and isinstance(value.value.value, cross4_hist_ast.Attribute)
                and value.value.value.attr == "modified"):
            continue
        slice_node = value.slice
        slice_value = getattr(slice_node, "value", None)
        if not (isinstance(slice_value, str) and slice_value == "integrals"):
            continue
        for target in node.targets:
            if (isinstance(target, cross4_hist_ast.Attribute)
                    and target.attr == "incoming_integrals"):
                result["incoming_integrals_assignment_count"] += 1
    result["passed"] = (
        result["source_present"] and result["AST_parsed"]
        and result["incoming_integrals_assignment_count"] == 1)
    return result


def cross4_hist_source_contract(source_texts):
    results = {}

def _cross4_substitution_map(record, mapping, variable, value):
    """Check a fixed field map; no search over graph nodes is performed."""
    if not isinstance(mapping, dict) or set(mapping) != set(RH_FIELD_CHANNELS):
        return False
    for name in RH_FIELD_CHANNELS:
        nodes = mapping.get(name)
        if not isinstance(nodes, list) or len(nodes) != 7:
            return False
        if not all(isinstance(node, int) for node in nodes):
            return False
        if not all(_cross4_function_substitution(record, node, variable, value)
                   for node in nodes):
            return False
    return True



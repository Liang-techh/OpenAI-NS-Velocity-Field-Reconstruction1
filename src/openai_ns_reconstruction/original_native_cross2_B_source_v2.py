def _cross4_path(value, *keys):
    current = value
    for key in keys:
        if not isinstance(current, dict):
            return None
        current = current.get(key)
    return current


def _cross4_row(record, number):
    if not isinstance(record, dict) or not isinstance(number, int):
        return None
    rows = record.get("exact_graph_nodes")
    if not isinstance(rows, list) or number < 0 or number >= len(rows):
        return None
    row = rows[number]
    return row if isinstance(row, dict) else None


def _cross4_row_is(record, number, expected):
    row = _cross4_row(record, number)
    return isinstance(row, dict) and all(row.get(key) == value for key, value in expected.items())


def _cross4_archive_auth(record, alias, raw_auth):
    """Require the caller's raw-byte authentication before using a record."""
    candidate = raw_auth.get(alias) if isinstance(raw_auth, dict) else None
    if not isinstance(candidate, dict):
        candidate = record if isinstance(record, dict) else {}
    digest = candidate.get("raw_sha256")
    if not isinstance(digest, str):
        digest = candidate.get("sha256")
    authenticated = candidate.get("raw_authenticated_before_decode")
    if authenticated is None:
        authenticated = candidate.get("authenticated_before_decode")
    return {
        "raw_sha256": digest.lower() if isinstance(digest, str) else None,
        "expected": RAW_ARCHIVE_SHA256.get(alias),
        "raw_authenticated_before_decode": authenticated is True,
        "passed": (isinstance(digest, str)
                    and digest.lower() == RAW_ARCHIVE_SHA256.get(alias)
                    and authenticated is True),
    }



def _cross4_norm_find_function(tree, name, owner=None):
    if not isinstance(tree, _cross4_norm_ast.AST):
        return None
    if owner is None:
        for node in getattr(tree, "body", ()):
            if isinstance(node, (_cross4_norm_ast.FunctionDef,
                                 _cross4_norm_ast.AsyncFunctionDef)) \
                    and node.name == name:
                return node
        return None
    for node in getattr(tree, "body", ()):
        if isinstance(node, _cross4_norm_ast.ClassDef) and node.name == owner:
            for method in node.body:
                if isinstance(method, (_cross4_norm_ast.FunctionDef,
                                       _cross4_norm_ast.AsyncFunctionDef)) \
                        and method.name == name:
                    return method
    return None



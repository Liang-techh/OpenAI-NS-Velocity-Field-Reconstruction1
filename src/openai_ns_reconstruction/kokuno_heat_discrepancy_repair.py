"""Executable heat-discrepancy repair primitive from the corrected Kokuno reader.

The pinned 2026-09-09 reconstruction replaces the far exterior by the exact
radial heat profile and repairs the three induced exterior discrepancies on an
earlier reserved swirl patch.  On that patch the source background is

    x_* = X / X_*,  E = e_* f x_*^(-1/2-lambda),  U = 0,

and the repair is

    delta E = e_* sum_i c_i(eta) beta_i(x_*).

After division by the source physical scales, the three exact discrepancy rows
are generated by delta(E^2)/(2X), -delta(E^2)/2, and sqrt(2X) delta E.  The
first two retain their quadratic terms; the third is linear.  Their linear
weights are exactly

    f x_*^(-3/2-lambda), -f x_*^(-1/2-lambda), sqrt(2) x_*^(1/2).

The source requires three ordered nonnegative compact bumps and proves the
resulting moment matrix invertible.  It does not prescribe repository-ready
numerical bump locations.  The concrete C-infinity bumps and coefficient bound
below are explicit autonomous numerical choices.  This module supplies only the
local repair map: the actual heat discrepancy, source outer scales and final
core-to-heat assembly remain missing.
"""


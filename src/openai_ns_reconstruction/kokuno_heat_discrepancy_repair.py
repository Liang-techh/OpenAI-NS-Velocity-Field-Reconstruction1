def _canonical_json(payload: dict[str, Any]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _finite_array(value: Any, name: str) -> np.ndarray:
    array = np.asarray(value, dtype=float)
    if not np.all(np.isfinite(array)):
        raise ValueError(f"{name} must contain only finite values")
    return array


def _coefficient_array(value: Any, limit: float) -> np.ndarray:
    coefficients = _finite_array(value, "coefficients")
    if coefficients.shape != (3,):
        raise ValueError("coefficients must have shape (3,)")
    if np.any(np.abs(coefficients) > limit + 1.0e-15):
        raise ValueError("repair coefficient exceeds the declared bound")
    return coefficients


def _cinfty_bump(x: np.ndarray, center: float) -> np.ndarray:
    values = np.asarray(x, dtype=float)
    s = (values - center) / _BUMP_HALF_WIDTH
    out = np.zeros_like(values)
    active = np.abs(s) < 1.0
    if np.any(active):
        sa = s[active]
        out[active] = np.exp(1.0 - 1.0 / (1.0 - sa * sa))
    return out


def _cinfty_bump_dx(x: np.ndarray, center: float) -> np.ndarray:
    values = np.asarray(x, dtype=float)
    s = (values - center) / _BUMP_HALF_WIDTH
    out = np.zeros_like(values)
    active = np.abs(s) < 1.0
    if np.any(active):
        sa = s[active]
        bump = np.exp(1.0 - 1.0 / (1.0 - sa * sa))
        out[active] = (
            bump
            * (-2.0 * sa / (1.0 - sa * sa) ** 2)
            / _BUMP_HALF_WIDTH
        )
    return out


@dataclass(frozen=True)
class HeatDiscrepancySolveResult:
    coefficients: tuple[float, float, float]
    target_normalized: tuple[float, float, float]
    achieved_normalized: tuple[float, float, float]
    residual_normalized: tuple[float, float, float]
    max_abs_residual: float
    nfev: int
    success: bool


@dataclass(frozen=True)
class KokunoHeatDiscrepancyRepair:
    """Bounded numerical realization of the source three-row heat repair map."""

    lambda_outer: float = 0.05
    quadrature_points: int = 192
    coefficient_limit: float = 0.05

    def __post_init__(self) -> None:
        lam = float(self.lambda_outer)
        if not math.isfinite(lam) or not (0.0 < lam <= 0.5):
            raise ValueError("lambda_outer must lie in (0,0.5]")
        if isinstance(self.quadrature_points, bool) or not isinstance(
            self.quadrature_points, (int, np.integer)
        ):
            raise TypeError("quadrature_points must be an integer")
        order = int(self.quadrature_points)
        if not 64 <= order <= 256:
            raise ValueError("quadrature_points must lie in [64,256]")
        limit = float(self.coefficient_limit)
        if not math.isfinite(limit) or not (0.0 < limit <= 0.2):
            raise ValueError("coefficient_limit must lie in (0,0.2]")
        object.__setattr__(self, "lambda_outer", lam)
        object.__setattr__(self, "quadrature_points", order)
        object.__setattr__(self, "coefficient_limit", limit)

    @staticmethod
    def source_f(eta: Any) -> np.ndarray:
        values = _finite_array(eta, "eta")
        if np.any(np.abs(values) > 1.0):
            raise ValueError("eta must lie in [-1,1]")
        return 1.0 / (1.0 + values * values)

    @staticmethod
    def _validate_f(f_eta: float) -> float:
        value = float(f_eta)
        if not math.isfinite(value) or value <= 0.0:
            raise ValueError("f_eta must be positive and finite")
        return value

    def _quadrature(self) -> tuple[np.ndarray, np.ndarray]:
        nodes, weights = leggauss(self.quadrature_points)
        half = 0.5 * (_X_STAR_MAX - _X_STAR_MIN)
        center = 0.5 * (_X_STAR_MAX + _X_STAR_MIN)
        x = center + half * nodes
        return np.asarray(x), np.asarray(half * weights)

    @staticmethod
    def basis_values(x_star: Any) -> np.ndarray:
        values = _finite_array(x_star, "x_star")
        return np.stack([_cinfty_bump(values, c) for c in _BUMP_CENTERS], axis=0)

    @staticmethod
    def basis_derivatives(x_star: Any) -> np.ndarray:
        values = _finite_array(x_star, "x_star")
        return np.stack([_cinfty_bump_dx(values, c) for c in _BUMP_CENTERS], axis=0)

    def correction_over_e_star(self, x_star: Any, coefficients: Any) -> np.ndarray:
        values = _finite_array(x_star, "x_star")
        coeff = _coefficient_array(coefficients, self.coefficient_limit)
        return np.asarray(np.tensordot(coeff, self.basis_values(values), axes=(0, 0)))

    def correction_derivative_over_e_star(self, x_star: Any, coefficients: Any) -> np.ndarray:
        values = _finite_array(x_star, "x_star")
        coeff = _coefficient_array(coefficients, self.coefficient_limit)
        return np.asarray(
            np.tensordot(coeff, self.basis_derivatives(values), axes=(0, 0))
        )

    def background_over_e_star(self, x_star: Any, f_eta: float) -> np.ndarray:
        values = _finite_array(x_star, "x_star")
        if np.any(values <= 0.0):
            raise ValueError("x_star must be positive")
        f_value = self._validate_f(f_eta)
        return f_value * values ** (-0.5 - self.lambda_outer)

    def corrected_profile(
        self,
        x_star: Any,
        *,
        f_eta: float,
        e_star: float,
        coefficients: Any,
    ) -> dict[str, np.ndarray]:
        values = _finite_array(x_star, "x_star")
        e_scale = float(e_star)
        if not math.isfinite(e_scale) or e_scale <= 0.0:
            raise ValueError("e_star must be positive and finite")
        base = self.background_over_e_star(values, f_eta)
        correction = self.correction_over_e_star(values, coefficients)
        corrected = base + correction
        if np.any(corrected <= 0.0):
            raise ValueError("repair would violate positivity of E")
        derivative_base = (-0.5 - self.lambda_outer) * base / values
        derivative_correction = self.correction_derivative_over_e_star(values, coefficients)
        return {
            "E": e_scale * corrected,
            "E_x_star": e_scale * (derivative_base + derivative_correction),
            "delta_E": e_scale * correction,
            "delta_E_x_star": e_scale * derivative_correction,
        }

    def normalized_increment(self, coefficients: Any, *, f_eta: float) -> np.ndarray:
        """Return the exact three source discrepancy increments after scaling.

        Order is ``(delta_Cp/e_*^2, delta_S/(X_*e_*^2),
        delta_I/(X_*^(3/2)e_*))``.
        """

        coeff = _coefficient_array(coefficients, self.coefficient_limit)
        f_value = self._validate_f(f_eta)
        x, weights = self._quadrature()
        basis = self.basis_values(x)
        g = np.tensordot(coeff, basis, axes=(0, 0))
        b = f_value * x ** (-0.5 - self.lambda_outer)
        delta_square = 2.0 * b * g + g * g
        integrands = np.stack(
            [
                0.5 * delta_square / x,
                -0.5 * delta_square,
                np.sqrt(2.0 * x) * g,
            ],
            axis=0,
        )
        return np.asarray(integrands @ weights, dtype=float)

    def coefficient_jacobian(self, coefficients: Any, *, f_eta: float) -> np.ndarray:
        """Analytic Jacobian of :meth:`normalized_increment`."""

        coeff = _coefficient_array(coefficients, self.coefficient_limit)
        f_value = self._validate_f(f_eta)
        x, weights = self._quadrature()
        basis = self.basis_values(x)
        g = np.tensordot(coeff, basis, axes=(0, 0))
        b = f_value * x ** (-0.5 - self.lambda_outer)
        jac = np.empty((3, 3), dtype=float)
        for column, beta in enumerate(basis):
            jac[:, column] = np.asarray(
                [
                    np.sum(weights * (b + g) * beta / x),
                    -np.sum(weights * (b + g) * beta),
                    np.sum(weights * np.sqrt(2.0 * x) * beta),
                ]
            )
        return jac

    def linear_weights(self, x_star: Any, *, f_eta: float) -> np.ndarray:
        """Expose the three source linear weights for direct provenance checks."""

        x = _finite_array(x_star, "x_star")
        if np.any(x <= 0.0):
            raise ValueError("x_star must be positive")
        f_value = self._validate_f(f_eta)
        lam = self.lambda_outer
        return np.stack(
            [
                f_value * x ** (-1.5 - lam),
                -f_value * x ** (-0.5 - lam),
                np.sqrt(2.0) * np.sqrt(x),
            ],
            axis=0,
        )

    @staticmethod
    def physical_increment(
        normalized: Any, *, X_star: float, e_star: float
    ) -> np.ndarray:
        values = _finite_array(normalized, "normalized")
        if values.shape != (3,):
            raise ValueError("normalized must have shape (3,)")
        X_scale = float(X_star)
        e_scale = float(e_star)
        if not math.isfinite(X_scale) or X_scale <= 0.0:
            raise ValueError("X_star must be positive and finite")
        if not math.isfinite(e_scale) or e_scale <= 0.0:
            raise ValueError("e_star must be positive and finite")
        return values * np.asarray(
            [e_scale * e_scale, X_scale * e_scale * e_scale, X_scale ** 1.5 * e_scale]
        )

    def physical_profile_correction(
        self,
        X: Any,
        *,
        X_star: float,
        e_star: float,
        coefficients: Any,
    ) -> dict[str, np.ndarray]:
        values = _finite_array(X, "X")
        X_scale = float(X_star)
        e_scale = float(e_star)
        if not math.isfinite(X_scale) or X_scale <= 0.0:
            raise ValueError("X_star must be positive and finite")
        if not math.isfinite(e_scale) or e_scale <= 0.0:
            raise ValueError("e_star must be positive and finite")
        x_star = values / X_scale
        correction = self.correction_over_e_star(x_star, coefficients)
        derivative = self.correction_derivative_over_e_star(x_star, coefficients)
        return {
            "delta_E": e_scale * correction,
            "delta_E_X": e_scale * derivative / X_scale,
        }

    def solve(
        self,
        target_normalized: Any,
        *,
        f_eta: float,
        residual_tolerance: float = 2.0e-11,
    ) -> HeatDiscrepancySolveResult:
        """Solve a caller-supplied *small* normalized heat discrepancy.

        The real target is intentionally not synthesized here.  It must come
        from the future source outer/heat replacement assembly.
        """

        target = _finite_array(target_normalized, "target_normalized")
        if target.shape != (3,):
            raise ValueError("target_normalized must have shape (3,)")
        f_value = self._validate_f(f_eta)
        tolerance = float(residual_tolerance)
        if not math.isfinite(tolerance) or not (0.0 < tolerance <= 1.0e-7):
            raise ValueError("residual_tolerance must lie in (0,1e-7]")

        zero = np.zeros(3, dtype=float)
        linear = self.coefficient_jacobian(zero, f_eta=f_value)
        singular_values = np.linalg.svd(linear, compute_uv=False)
        if singular_values[-1] <= 1.0e-12 * singular_values[0]:
            raise ValueError("source heat-repair linearized map is numerically rank deficient")
        initial = np.linalg.solve(linear, target)
        if np.any(np.abs(initial) > 0.9 * self.coefficient_limit):
            raise ValueError("target is too large for the declared local repair bound")

        def residual(c: np.ndarray) -> np.ndarray:
            return self.normalized_increment(c, f_eta=f_value) - target

        def jacobian(c: np.ndarray) -> np.ndarray:
            return self.coefficient_jacobian(c, f_eta=f_value)

        result = least_squares(
            residual,
            initial,
            jac=jacobian,
            bounds=(-self.coefficient_limit, self.coefficient_limit),
            xtol=1.0e-13,
            ftol=1.0e-13,
            gtol=1.0e-13,
            max_nfev=80,
        )
        coefficients = np.asarray(result.x, dtype=float)
        achieved = self.normalized_increment(coefficients, f_eta=f_value)
        residual_values = achieved - target
        max_abs = float(np.max(np.abs(residual_values)))
        x, _ = self._quadrature()
        base = self.background_over_e_star(x, f_value)
        correction = self.correction_over_e_star(x, coefficients)
        positive = bool(np.all(base + correction > 0.0))
        success = bool(result.success and positive and max_abs <= tolerance)
        if not success:
            raise ValueError(
                "bounded heat-discrepancy solve did not close within the declared local contract"
            )
        return HeatDiscrepancySolveResult(
            coefficients=tuple(float(v) for v in coefficients),
            target_normalized=tuple(float(v) for v in target),
            achieved_normalized=tuple(float(v) for v in achieved),
            residual_normalized=tuple(float(v) for v in residual_values),
            max_abs_residual=max_abs,
            nfev=int(result.nfev),
            success=True,
        )

    def _unsigned_payload(self) -> dict[str, Any]:
        return {
            "schema": SCHEMA,
            "provenance": {
                "repository": SOURCE_REPOSITORY,
                "commit": SOURCE_COMMIT,
                "path": SOURCE_PATH,
                "corrected_release": CORRECTED_RELEASE,
                "corrected_release_date": CORRECTED_RELEASE_DATE,
            },
            "source_formulas": dict(_SOURCE_FORMULAS),
            "autonomous_numerics": {
                "x_star_interval": [_X_STAR_MIN, _X_STAR_MAX],
                "bump_centers": list(_BUMP_CENTERS),
                "bump_half_width": _BUMP_HALF_WIDTH,
                "lambda_outer": self.lambda_outer,
                "quadrature_points": self.quadrature_points,
                "coefficient_limit": self.coefficient_limit,
            },
            "truth_boundary": dict(_TRUTH_BOUNDARY),
        }

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self._unsigned_payload_json().encode("utf-8")).hexdigest()

    def _unsigned_payload_json(self) -> str:
        return _canonical_json(self._unsigned_payload())

    def to_payload(self) -> dict[str, Any]:
        payload = self._unsigned_payload()
        payload["sha256"] = self.sha256
        return payload

    @classmethod
    def from_payload(cls, payload: dict[str, Any]) -> "KokunoHeatDiscrepancyRepair":
        if not isinstance(payload, dict):
            raise TypeError("payload must be a dictionary")
        if payload.get("schema") != SCHEMA:
            raise ValueError("unexpected heat-discrepancy repair schema")
        expected_provenance = {
            "repository": SOURCE_REPOSITORY,
            "commit": SOURCE_COMMIT,
            "path": SOURCE_PATH,
            "corrected_release": CORRECTED_RELEASE,
            "corrected_release_date": CORRECTED_RELEASE_DATE,
        }
        if payload.get("provenance") != expected_provenance:
            raise ValueError("source provenance mismatch")
        if payload.get("source_formulas") != _SOURCE_FORMULAS:
            raise ValueError("source formula contract mismatch")
        if payload.get("truth_boundary") != _TRUTH_BOUNDARY:
            raise ValueError("truth boundary mismatch")
        numerics = payload.get("autonomous_numerics")
        if not isinstance(numerics, dict):
            raise ValueError("autonomous_numerics is missing")
        expected_fixed = {
            "x_star_interval": [_X_STAR_MIN, _X_STAR_MAX],
            "bump_centers": list(_BUMP_CENTERS),
            "bump_half_width": _BUMP_HALF_WIDTH,
        }
        for key, value in expected_fixed.items():
            if numerics.get(key) != value:
                raise ValueError(f"autonomous numeric contract mismatch for {key}")
        repair = cls(
            lambda_outer=float(numerics["lambda_outer"]),
            quadrature_points=int(numerics["quadrature_points"]),
            coefficient_limit=float(numerics["coefficient_limit"]),
        )
        if repair.to_payload() != payload:
            raise ValueError("heat-discrepancy repair payload hash or content mismatch")
        return repair

    def save_json(self, path: str | Path) -> Path:
        destination = Path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(
            json.dumps(self.to_payload(), indent=2, sort_keys=True, allow_nan=False) + "\n",
            encoding="utf-8",
        )
        return destination

    @classmethod
    def load_json(cls, path: str | Path) -> "KokunoHeatDiscrepancyRepair":
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls.from_payload(payload)

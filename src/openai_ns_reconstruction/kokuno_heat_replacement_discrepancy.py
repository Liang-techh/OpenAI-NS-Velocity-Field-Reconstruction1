def _canonical_json(payload: dict[str, Any]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _finite_array(value: Any, name: str) -> np.ndarray:
    array = np.asarray(value, dtype=float)
    if not np.all(np.isfinite(array)):
        raise ValueError(f"{name} must contain only finite values")
    return array


def _flat_step(value: Any) -> np.ndarray:
    """The source C-infinity step sigma, evaluated without endpoint overflow."""

    s = _finite_array(value, "step_argument")
    out = np.zeros_like(s)
    out[s >= 1.0] = 1.0
    active = (s > 0.0) & (s < 1.0)
    if np.any(active):
        a = s[active]
        left = np.exp(-1.0 / (a * a))
        right = np.exp(-1.0 / ((1.0 - a) ** 2))
        out[active] = left / (left + right)
    return out


@dataclass(frozen=True)
class KokunoHeatReplacementDiscrepancy:
    """Evaluate the source heat-tail moment discrepancy for explicit tail scales."""

    h: float = 0.005
    X_tail: float = 1000.0
    c_inf: float = 1.0
    rho_o: float = 0.00025
    heat_quadrature_order: int = 96
    transition_quadrature_order: int = 192
    tail_quadrature_order: int = 96

    def __post_init__(self) -> None:
        h = float(self.h)
        X_tail = float(self.X_tail)
        c_inf = float(self.c_inf)
        rho_o = float(self.rho_o)
        if not math.isfinite(h) or not (0.0 < h < 1.0e-2):
            raise ValueError("h must satisfy the source construction bound 0<h<1e-2")
        if not math.isfinite(X_tail) or X_tail <= 0.0:
            raise ValueError("X_tail must be positive and finite")
        if not math.isfinite(c_inf) or c_inf <= 0.0:
            raise ValueError("c_inf must be positive and finite")
        if not math.isfinite(rho_o) or not (0.0 < rho_o < 0.1):
            raise ValueError("rho_o must lie in (0,0.1)")
        for name, value, lo, hi in (
            ("heat_quadrature_order", self.heat_quadrature_order, 32, 256),
            ("transition_quadrature_order", self.transition_quadrature_order, 64, 512),
            ("tail_quadrature_order", self.tail_quadrature_order, 32, 256),
        ):
            if isinstance(value, bool) or not isinstance(value, (int, np.integer)):
                raise TypeError(f"{name} must be an integer")
            if not lo <= int(value) <= hi:
                raise ValueError(f"{name} must lie in [{lo},{hi}]")
        object.__setattr__(self, "h", h)
        object.__setattr__(self, "X_tail", X_tail)
        object.__setattr__(self, "c_inf", c_inf)
        object.__setattr__(self, "rho_o", rho_o)
        object.__setattr__(self, "heat_quadrature_order", int(self.heat_quadrature_order))
        object.__setattr__(
            self, "transition_quadrature_order", int(self.transition_quadrature_order)
        )
        object.__setattr__(self, "tail_quadrature_order", int(self.tail_quadrature_order))
        if self.max_terminal_log_slope() >= 0.25 * h:
            raise ValueError("rho_o violates the source terminal bound f_o'/f_o<h/4")

    @property
    def A(self) -> float:
        return 0.5 + self.h

    @property
    def X_K(self) -> float:
        return math.exp(0.2) * self.X_tail

    @property
    def X_b(self) -> float:
        return math.exp(3.0) * self.X_tail

    def _heat(self) -> KokunoHeatExteriorProfile:
        return KokunoHeatExteriorProfile(
            h=self.h, c_inf=self.c_inf, quadrature_order=self.heat_quadrature_order
        )

    @staticmethod
    def chi_K(y: Any) -> np.ndarray:
        """Autonomous flat realization of the source .2-to-.5 transition."""

        values = _finite_array(y, "y")
        return _flat_step((values - 0.2) / 0.3)

    def psi_o(self, y: Any) -> np.ndarray:
        values = _finite_array(y, "y")
        return 1.0 - _flat_step((values - 1.0) / 2.0)

    def f_o(self, y: Any) -> np.ndarray:
        return 1.0 - self.rho_o * self.psi_o(y)

    def max_terminal_log_slope(self) -> float:
        # The bound is only used as a construction guard.  A deterministic,
        # high-resolution screen is sufficient for this executable realization.
        y = np.linspace(0.0, 3.0, 8193)
        f = self.f_o(y)
        dy = y[1] - y[0]
        derivative = np.gradient(f, dy, edge_order=2)
        return float(np.max(np.maximum(derivative / f, 0.0)))

    def reference_tail_scales(self) -> dict[str, float]:
        """Return source-defined X_K/X_b and the explicit reference amplitude at X_K."""

        y_k = 0.2
        e_k = self.c_inf * self.X_K ** (-self.A) * float(self.f_o(y_k))
        return {"X_K": self.X_K, "X_b": self.X_b, "e_K": e_k}

    def _heat_minus_one_over_z(self, z: Any) -> np.ndarray:
        """Stable ``(Hcal(z)-1)/z`` including its exact one-sided z=0 value."""

        values = _finite_array(z, "z")
        if np.any(values < 0.0):
            raise ValueError("heat argument z must be nonnegative")
        heat = self._heat()
        out = np.empty_like(values)
        small = values <= 1.0e-4
        if np.any(~small):
            z_big = values[~small]
            out[~small] = (heat.heat_factor(z_big) - 1.0) / z_big
        if np.any(small):
            z_small = values[small]
            derivatives = [
                float(heat.heat_factor(np.asarray(0.0), derivative=k))
                for k in range(1, 5)
            ]
            out[small] = (
                derivatives[0]
                + 0.5 * derivatives[1] * z_small
                + derivatives[2] * z_small * z_small / 6.0
                + derivatives[3] * z_small * z_small * z_small / 24.0
            )
        return out

    def _scalar_discrepancy(self, eta: float) -> np.ndarray:
        if not math.isfinite(eta) or abs(eta) > 1.0:
            raise ValueError("eta must lie in [-1,1]")
        d = 1.0 - eta * eta
        if d == 0.0:
            return np.zeros(3, dtype=float)

        nodes, weights = leggauss(self.transition_quadrature_order)
        y = 1.5 * (nodes + 1.0)
        weights = 1.5 * weights
        X = self.X_tail * np.exp(y)
        z = 2.0 * d / X
        ratio = self._heat_minus_one_over_z(z)
        heat_minus_one = z * ratio
        multiplier = self.chi_K(y) * heat_minus_one

        E_cl = self.c_inf * np.power(X, -self.A) * self.f_o(y)
        delta_square = E_cl * E_cl * (2.0 * multiplier + multiplier * multiplier)
        delta_E = E_cl * multiplier

        transition = np.asarray(
            [
                np.sum(weights * 0.5 * delta_square),
                np.sum(weights * (-0.5) * delta_square * X),
                np.sum(weights * np.sqrt(2.0 * X) * delta_E * X),
            ],
            dtype=float,
        )

        # For y>=3, chi_K=f_o=1 exactly.  Write Hcal-1=z*R(z) and
        # integrate each exponential factor with Gauss-Laguerre.  This avoids
        # catastrophic cancellation and the very long O(1/h) I_sub tail.
        s, w = roots_laguerre(self.tail_quadrature_order)
        X0 = self.X_b
        z0 = 2.0 * d / X0

        def laguerre_R(rate: float) -> np.ndarray:
            return self._heat_minus_one_over_z(z0 * np.exp(-s / rate))

        k_cp_1 = 2.0 * self.A + 1.0
        R = laguerre_R(k_cp_1)
        tail_cp = (
            self.c_inf**2
            * d
            * X0 ** (-k_cp_1)
            / k_cp_1
            * np.sum(w * R)
        )
        k_cp_2 = 2.0 * self.A + 2.0
        R = laguerre_R(k_cp_2)
        tail_cp += (
            2.0
            * self.c_inf**2
            * d**2
            * X0 ** (-k_cp_2)
            / k_cp_2
            * np.sum(w * R * R)
        )

        k_s_1 = 1.0 + 2.0 * self.h
        R = laguerre_R(k_s_1)
        tail_s = (
            -2.0
            * self.c_inf**2
            * d
            * X0 ** (-k_s_1)
            / k_s_1
            * np.sum(w * R)
        )
        k_s_2 = 2.0 + 2.0 * self.h
        R = laguerre_R(k_s_2)
        tail_s += (
            -2.0
            * self.c_inf**2
            * d**2
            * X0 ** (-k_s_2)
            / k_s_2
            * np.sum(w * R * R)
        )

        R = laguerre_R(self.h)
        tail_i = (
            2.0
            * math.sqrt(2.0)
            * self.c_inf
            * d
            * X0 ** (-self.h)
            / self.h
            * np.sum(w * R)
        )
        return transition + np.asarray([tail_cp, tail_s, tail_i], dtype=float)

    def discrepancy(self, eta: Any) -> np.ndarray:
        """Return ``[...,3]`` physical ``(Delta C_p, Delta S, Delta I_sub)``."""

        values = _finite_array(eta, "eta")
        if np.any(np.abs(values) > 1.0):
            raise ValueError("eta must lie in [-1,1]")
        flat = values.reshape(-1)
        result = np.stack([self._scalar_discrepancy(float(v)) for v in flat], axis=0)
        return result.reshape(values.shape + (3,))

    def normalized_repair_target(
        self, eta: Any, *, X_star: float, e_star: float
    ) -> np.ndarray:
        """Return the source repair target that cancels the heat discrepancy."""

        X_scale = float(X_star)
        e_scale = float(e_star)
        if not math.isfinite(X_scale) or X_scale <= 0.0:
            raise ValueError("X_star must be positive and finite")
        if not math.isfinite(e_scale) or e_scale <= 0.0:
            raise ValueError("e_star must be positive and finite")
        scales = np.asarray(
            [e_scale**2, X_scale * e_scale**2, X_scale**1.5 * e_scale],
            dtype=float,
        )
        return -self.discrepancy(eta) / scales


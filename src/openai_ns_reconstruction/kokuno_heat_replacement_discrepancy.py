"""Source heat-replacement discrepancy evaluator for the Kokuno outer schedule.

The corrected 2026-09-09 reader replaces the far power-law swirl by the
radial heat solution.  With ``y=log(X/X_tail)`` it sets

    X_K = exp(.2) X_tail,  X_b = exp(3) X_tail,
    chi_K = 0 for y<=.2, chi_K = 1 for y>=.5,
    E_new = E_cl * (1 + chi_K (Hcal(2d/X)-1)),

where ``d=1-eta^2`` and, on the terminal tail,

    E_cl = c_inf X^(-A) f_o(y),
    f_o = 1-rho_o psi_o, psi_o = 1-sigma((y-1)/2),
    A=1/2+h.

This module evaluates the three *actual heat-replacement* moment changes
``(Delta C_p, Delta S, Delta I_sub)`` generated by those formulas.  The flat
choice ``chi_K=sigma((y-.2)/.3)`` is a deterministic autonomous realization
of the source's allowed transition; the source only fixes its support/end
values.  ``X_tail``, ``c_inf`` and ``rho_o`` remain explicit schedule inputs:
this module does not claim to have recovered the source existence proof's
hidden numerical choices.

The result can be converted to the normalized target required by
``KokunoHeatDiscrepancyRepair``.  That conversion still requires the earlier
reserved-patch scales ``X_star,e_star`` from the outer schedule, so this is one
step short of a globally matched leading field.
"""


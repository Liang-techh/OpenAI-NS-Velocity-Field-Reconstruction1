    def sha256(self) -> str:
        return hashlib.sha256(_canonical_json(self._unsigned_payload()).encode()).hexdigest()

    def to_payload(self) -> dict[str, Any]:
        payload = self._unsigned_payload()
        payload["sha256"] = self.sha256
        return payload

    @classmethod
    def from_payload(cls, payload: dict[str, Any]) -> "KokunoHeatReplacementDiscrepancy":
        if not isinstance(payload, dict) or payload.get("schema") != SCHEMA:
            raise ValueError("unexpected heat-replacement-discrepancy schema")
        expected_provenance = {
            "repository": SOURCE_REPOSITORY,
            "commit": SOURCE_COMMIT,
            "path": SOURCE_PATH,
            "corrected_release": CORRECTED_RELEASE,
            "corrected_release_date": CORRECTED_RELEASE_DATE,
        }
        if payload.get("provenance") != expected_provenance:
            raise ValueError("source provenance mismatch")
        if payload.get("source_formulas") != _SOURCE_FORMULAS:
            raise ValueError("source formula contract mismatch")
        if payload.get("truth_boundary") != _TRUTH_BOUNDARY:
            raise ValueError("truth boundary mismatch")
        params = payload.get("parameters")
        if not isinstance(params, dict):
            raise ValueError("parameters are missing")
        obj = cls(**params)
        if obj.to_payload() != payload:
            raise ValueError("heat replacement discrepancy payload hash or content mismatch")
        return obj

    def save_json(self, path: str | Path) -> Path:
        destination = Path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(
            json.dumps(self.to_payload(), indent=2, sort_keys=True, allow_nan=False) + "\n",
            encoding="utf-8",
        )
        return destination

    @classmethod
    def load_json(cls, path: str | Path) -> "KokunoHeatReplacementDiscrepancy":
        return cls.from_payload(json.loads(Path(path).read_text(encoding="utf-8")))

"""Carrier-resolved autonomous Kokuno-structured public oscillatory candidate.

This is one repository-autonomous reparameterization of Agent-2's already
source-formula-bound public complete-curl pipeline.  It exists because Agent 4's
frozen black-box Cartesian FD4 audit resolved the project support after #539 but
still under-resolved the public carrier: the old autonomous background generated
large angular winding numbers even though the field is assembled through exact
vector-potential curls.

The source-displayed phase, carrier rounding, complete-curl, signed covariance,
partition, Q/epsilon schedule and physical scaling are unchanged.  Only the
repository-autonomous constant background realization is replaced by one bounded
choice that lowers the effective physical carrier frequencies.  This module
therefore does NOT claim Kokuno's unpublished positive-order background and does
NOT claim that the independent divergence audit passes until Agent 4 reruns the
unchanged protocol.
"""

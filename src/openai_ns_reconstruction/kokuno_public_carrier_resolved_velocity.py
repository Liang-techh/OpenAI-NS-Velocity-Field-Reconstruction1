from .kokuno_public_candidate_velocity import KokunoPublicCandidateOscillatoryVelocity

SCHEMA = "kokuno-public-carrier-resolved-oscillatory-velocity-v1"
PARENT_AGENT2_HEAD = "985d1c3fc43081d2d87feb1f0c27643cc4ebe75b"

# Repository-autonomous, source-compatible constants.  They are deliberately
# finite and frozen rather than exposed as another free optimization vector.

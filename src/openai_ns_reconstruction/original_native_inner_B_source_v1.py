def inner_digest(value):
    return inner_hashlib.sha256(inner_json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=True, allow_nan=False).encode()).hexdigest()


def inner_require(condition, message):
    if condition is not True:
        raise AssertionError(message)


def inner_emit(callback, events, stage, payload):
    frozen = inner_json.loads(inner_json.dumps(payload, allow_nan=False))
    events.append({'stage': stage, 'payload': frozen})
    if callback is not None:
        callback(stage, frozen)



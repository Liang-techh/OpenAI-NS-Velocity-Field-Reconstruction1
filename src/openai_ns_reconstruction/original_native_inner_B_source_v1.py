def _row(rows, index):
    return rows[index] if isinstance(rows, list) and isinstance(index, int) and 0 <= index < len(rows) and isinstance(rows[index], dict) else None


def _is(rows, index, **expected):
    row = _row(rows, index)
    return row is not None and all(row.get(key) == value for key, value in expected.items())


def _children(row):
    if not isinstance(row, dict):
        return ()
    result = []
    for key in ("arguments", "numerator", "denominator", "argument", "expression", "left", "right"):
        value = row.get(key)
        if isinstance(value, int):
            result.append(value)
        elif isinstance(value, list):
            result.extend(value for value in value if isinstance(value, int))
    return tuple(result)



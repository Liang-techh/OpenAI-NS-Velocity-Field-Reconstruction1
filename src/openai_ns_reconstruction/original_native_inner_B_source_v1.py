    """Validate one authenticated literal edge route; never search the graph."""
    spec = ROUTE_TABLE.get(route_key)
    if not isinstance(spec, dict) or not isinstance(rows, list):
        return False
    graph_name = spec.get("graph")
    if ROUTE_GRAPH_ROW_COUNTS.get(graph_name) != len(rows):
        return False
    if spec.get("archive_sha256") != RAW_ARCHIVE_SHA256.get(graph_name):
        return False
    if spec.get("root") != root or spec.get("targets") != list(targets):
        return False
    paths = spec.get("paths")
    if not isinstance(paths, list) or len(paths) != len(targets):
        return False

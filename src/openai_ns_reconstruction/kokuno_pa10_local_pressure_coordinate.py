"""Cancellation-safe local-coordinate pressure API for selected PA.10 center.

This module is a narrow numerical interface layered on
:mod:`kokuno_pa10_selected_pressure_primitive`.  The corrected public Kokuno
reconstruction uses the selected stationary point ``eta_*`` and the very narrow
pressure layer generated by the repository-autonomous ``Lambda``.  Agent-4
cross-audit showed that an eta-only binary64 public API cannot support a strict
fundamental-theorem check once the natural layer width ``Lambda**(-1/2)`` is
comparable to only O(10^4) eta ulps.

The local coordinate

    s = sqrt(Lambda) * (eta - eta_*)

keeps the narrow layer O(1).  Values are evaluated directly in ``s`` without
first materializing ``eta_* + s/sqrt(Lambda)``.  The public source formulas are
unchanged.  In particular,

    d/deta = sqrt(Lambda) d/ds,
    p_eta = sqrt(Lambda) p_s.

The stationary-root polynomial factorization already introduced by Agent 1 is
re-expressed in the offset ``delta=s/sqrt(Lambda)``.  The local phase is then
integrated in ``s`` using

    d(log g)/ds = sqrt(Lambda) zeta_*(eta_* + s/sqrt(Lambda)).

This is a repository-selected numerical representation, not recovered hidden
Kokuno data and not a source radius-one-ball certificate.  Source M/K, B0/T_sh,
PA.16, global matched pressure, global leading velocity and PDE validation all
remain outside this module.
"""


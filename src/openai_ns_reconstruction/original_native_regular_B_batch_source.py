"""Root-owned unexecuted composition for authenticated endpoint fragments."""

import hashlib as root_hashlib
import json as root_json


def root_require(condition, message):
    if not condition:
        raise AssertionError(message)


def root_digest(value):
    return root_hashlib.sha256(root_json.dumps(
        value, sort_keys=True, separators=(',', ':'), ensure_ascii=True,
        allow_nan=False).encode('utf-8')).hexdigest()


def root_emit(callback, events, stage, payload):
    frozen = root_json.loads(root_json.dumps(payload, allow_nan=False))
    events.append({'stage': stage, 'payload': frozen})
    if callback is not None:
        callback(stage, frozen)


def root_fragment_emit(callback, events, group, stage, payload):
    qualified = stage if stage.startswith(group + '.') else group + '.' + stage
    root_emit(callback, events, qualified, payload)


def root_authenticate(records, expected_input_digest):
    predicates = {
        'record_names': isinstance(records, dict) and set(records) == set(RECORD_NAMES),
        'input_digest': root_digest(records) == expected_input_digest,
    }
    if not predicates['record_names']:
        return {'passed': False, 'predicates': predicates}
    for name in RECORD_NAMES:
        value = records[name]
        text = value.get('source_text')
        predicates[name] = (
            isinstance(text, str)
            and value.get('raw_sha256') == RECORD_HASHES[name]
            and value.get('decoded_sha256') == DECODED_RECORD_HASHES[name]
            and root_hashlib.sha256(text.encode('utf-8')).hexdigest()
            == DECODED_RECORD_HASHES[name]
            and value.get('raw_authenticated_before_decode') is True
            and value.get('is_gzip') is name.endswith('.gz'))
    return {'passed': all(value is True for value in predicates.values()),
            'predicates': predicates, 'raw_SHA_before_decode': True,
            'numeric_values_computed': False}



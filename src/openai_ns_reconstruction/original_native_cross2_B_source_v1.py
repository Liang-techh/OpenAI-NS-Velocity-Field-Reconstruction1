def cross3_hist_ast_assignment_counts(source_texts):
    """Count only fixed assignment signatures in the pinned source ASTs."""
    results = {}
    for alias in ("loop", "patch"):
        text = cross3_hist_text(cross3_hist_contract_value(source_texts, alias))
        counts = {
            "incoming_from_loop_correction": 0,
            "pressure_incoming_from_modified": 0,
            "rm_correction_assignment": 0,
        }
        if isinstance(text, str):
            try:
                tree = cross3_hist_ast.parse(text, filename=alias + ".py")
                for node in cross3_hist_ast.walk(tree):
                    if not isinstance(node, cross3_hist_ast.Assign):
                        continue
                    targets = node.targets
                    value = node.value
                    for target in targets:
                        if (isinstance(target, cross3_hist_ast.Attribute)
                                and target.attr == "incoming"
                                and isinstance(value, cross3_hist_ast.Attribute)
                                and value.attr == "Rm_correction"):
                            counts["incoming_from_loop_correction"] += 1
                        if (isinstance(target, cross3_hist_ast.Attribute)
                                and target.attr == "incoming_integrals"
                                and isinstance(value, cross3_hist_ast.Subscript)
                                and isinstance(value.value, cross3_hist_ast.Attribute)
                                and value.value.attr == "modified"):
                            counts["pressure_incoming_from_modified"] += 1
                        if (isinstance(target, cross3_hist_ast.Attribute)
                                and target.attr == "Rm_correction"):
                            counts["rm_correction_assignment"] += 1
            except (SyntaxError, TypeError, ValueError):
                pass
        results[alias] = counts
    return results



def cross3_hist_text(value):
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        for key in ("source_text", "text", "body", "source"):
            text = value.get(key)
            if isinstance(text, str):
                return text
    return None


def cross3_hist_sha256(text):
    if not isinstance(text, str):
        return None
    return cross3_hist_hashlib.sha256(text.encode("utf-8")).hexdigest()


def cross3_hist_contract_value(mapping, alias):
    if not isinstance(mapping, dict):
        return None
    if alias in mapping:
        return mapping.get(alias)
    if alias == "c6":
        return mapping.get("background")
    return None


def cross3_hist_source_contracts(source_texts, source_contracts):
    """Authenticate the five pinned creator files using parsed AST bodies."""
    results = {}
    for alias, expected in cross3_hist_CREATOR_SOURCE_SHA256.items():
        text = cross3_hist_text(cross3_hist_contract_value(source_texts, alias))
        supplied = cross3_hist_contract_value(source_contracts, alias)
        parsed = False
        tree = None
        top_level_names = []
        body_sha256 = {}
        if text:
            try:
                tree = cross3_hist_ast.parse(text, filename=alias + ".py")
                parsed = True
                top_level_names = sorted(
                    node.name for node in tree.body
                    if isinstance(node, (cross3_hist_ast.FunctionDef,
                                         cross3_hist_ast.AsyncFunctionDef,
                                         cross3_hist_ast.ClassDef)))
                for name in cross3_hist_SOURCE_AST_PIN_NAMES[alias]:
                    node = next((item for item in tree.body
                                 if getattr(item, "name", None) == name), None)
                    if node is not None:
                        body_sha256[name] = cross3_hist_sha256(
                            cross3_hist_ast_dump(node))
            except (SyntaxError, TypeError, ValueError):
                parsed = False
        digest = cross3_hist_sha256(text)
        markers = {
            marker: isinstance(text, str) and marker in text
            for marker in cross3_hist_SOURCE_BODY_MARKERS[alias]
        }
        expected_body = cross3_hist_SOURCE_AST_PIN_SHA256[alias]
        actual_body = body_sha256.get(cross3_hist_SOURCE_AST_PIN_NAMES[alias][0])
        body_pin = actual_body == expected_body
        required_names = all(name in top_level_names
                             for name in cross3_hist_SOURCE_AST_REQUIRED_NAMES[alias])

        supplied_sha = None
        supplied_ast = None
        supplied_passed = False
        if isinstance(supplied, dict):
            supplied_sha = (supplied.get("sha256")
                            or supplied.get("creator_sha256")
                            or supplied.get("actual_sha256"))
            supplied_ast = (supplied.get("AST_parsed")
                            if "AST_parsed" in supplied else supplied.get("ast_parsed"))
            supplied_passed = supplied.get("passed") is True
            if not supplied_passed:
                supplied_passed = (supplied.get("hash_matches") is True
                                   and supplied_ast is True)
        supplied_hash_ok = (
            isinstance(supplied, dict)
            and (supplied_sha == expected
                 or (supplied.get("hash_matches") is True
                     and supplied.get("expected_sha256") == expected))
        )
        supplied_ast_ok = isinstance(supplied, dict) and supplied_ast is True
        results[alias] = {
            "present": isinstance(text, str) and bool(text),
            "sha256": digest,
            "expected_sha256": expected,
            "hash_matches": digest == expected,
            "AST_parsed": parsed,
            "top_level_names": top_level_names,
            "required_ast_names": list(cross3_hist_SOURCE_AST_REQUIRED_NAMES[alias]),
            "required_ast_names_present": required_names,
            "pinned_ast_body_sha256": actual_body,
            "pinned_ast_body_expected_sha256": expected_body,
            "pinned_ast_body_matches": body_pin,
            "fixed_source_markers": markers,
            "source_contract_present": isinstance(supplied, dict),
            "source_contract_hash_ok": supplied_hash_ok,
            "source_contract_ast_ok": supplied_ast_ok,
            "source_contract_passed": supplied_passed,
            "passed": bool(
                isinstance(text, str) and bool(text) and digest == expected
                and parsed and required_names and body_pin and all(markers.values())
                and supplied_hash_ok and supplied_ast_ok and supplied_passed
            ),
        }
    return results


def cross3_hist_ast_dump(node):
    return cross3_hist_ast.dump(node, include_attributes=False)


def cross3_hist_binding(record, alias):
    if not isinstance(record, dict):
        return None
    key = cross3_hist_ARCHIVE_BINDING_KEYS[alias]
    binding = record.get(key)
    if isinstance(binding, dict):
        return binding
    # Permit a caller to pass the binding itself, while keeping the path
    # fixed and requiring the full record for graph rows elsewhere.
    if isinstance(record.get("charts"), dict) or isinstance(record.get("chart"), dict):
        return record
    return None


def cross3_hist_row(record, number):
    if not isinstance(record, dict) or not isinstance(number, int):
        return None
    rows = record.get("exact_graph_nodes")
    if not isinstance(rows, list) or number < 0 or number >= len(rows):
        return None
    row = rows[number]
    return row if isinstance(row, dict) else None


def cross3_hist_archive_contract(record, alias):
    binding = cross3_hist_binding(record, alias)
    raw = None
    if isinstance(record, dict):
        for key in ("raw_sha256", "raw_archive_sha256", "archive_raw_sha256"):
            if isinstance(record.get(key), str):
                raw = record[key].lower()
                break
    authenticated = (
        isinstance(record, dict)
        and (record.get("raw_authenticated_before_decode") is True
             or record.get("raw_sha256_checked_before_decode") is True
             or record.get("raw_sha256_checked_before_decode_by_caller") is True)
    )
    family_ok = isinstance(record, dict) and record.get("source_family") == cross3_hist_SOURCE_FAMILY
    rows_ok = isinstance(record, dict) and isinstance(record.get("exact_graph_nodes"), list)
    expected_raw = cross3_hist_RAW_ARCHIVE_SHA256[alias]
    return {
        "source_family": family_ok,
        "binding_key": cross3_hist_ARCHIVE_BINDING_KEYS[alias],
        "binding_present": isinstance(binding, dict),
        "exact_graph_nodes_present": rows_ok,
        "raw_sha256": raw,
        "raw_sha256_expected": expected_raw,
        "raw_sha256_matches": raw == expected_raw,
        "raw_authenticated_before_decode": authenticated,
        "passed": bool(family_ok and isinstance(binding, dict) and rows_ok
                       and raw == expected_raw and authenticated),
    }


def cross3_hist_path(value, *keys):
    current = value
    for key in keys:
        if not isinstance(current, dict):
            return None
        current = current.get(key)
    return current


def cross3_hist_equal(actual, expected):
    return actual == expected


def cross3_hist_contains(actual, expected):
    """Compare a fixed nested row map without traversing unrelated graph data."""
    if isinstance(expected, dict):
        return isinstance(actual, dict) and all(
            key in actual and cross3_hist_contains(actual[key], value)
            for key, value in expected.items())
    return actual == expected


def cross3_hist_rows(record, numbers, expected_operation=None):
    rows = [cross3_hist_row(record, number) for number in numbers]
    if expected_operation is None:
        return rows
    return all(isinstance(row, dict) and row.get("operation") == expected_operation
               for row in rows)


def cross3_hist_substitutions(record, numbers, expressions, variable, value):
    if not isinstance(numbers, list) or not isinstance(expressions, list):
        return False
    if len(numbers) != len(expressions):
        return False
    checks = []
    for number, expression in zip(numbers, expressions):
        row = cross3_hist_row(record, number)
        checks.append(
            isinstance(row, dict)
            and row.get("operation") == "function_substitution"
            and row.get("expression") == expression
            and row.get("variable") == variable
            and row.get("value") == value
            and row.get("Z_independent_substitution") is True
        )
    return bool(checks) and all(checks)


def cross3_hist_integral_rows(record, numbers, variable, lower, upper,
                               chart, rates, measure_key):
    checks = []
    for order, (number, rate) in enumerate(zip(numbers, rates)):
        row = cross3_hist_row(record, number)
        checks.append(
            isinstance(row, dict)
            and row.get("operation") == "definite_integral"
            and row.get("variable") == variable
            and row.get("lower") == lower
            and row.get("upper") == upper
            and row.get("exact_function_integral") is True
            and row.get("numerical_value_not_installed") is True
            and row.get("endpoint_independent_of_Z") is True
            and row.get("ordinary_slow_Z_derivative_order") == order
            and row.get("actual_finite_N_signed_correction") is True
            and row.get("original_rate") == rate
            and row.get("original_chart") == chart
            and row.get("physical_Jacobian_applied_once") is True
            and row.get("predecessor_memory_never_reset") is True
            and row.get(measure_key) in (True, "dt/t", "R*dx/x=Rm*dx",
                                         "R^2*dx/x=Rm^2*x*dx")
        )
    return bool(checks) and all(checks)


def cross3_hist_sum_once(record, numbers, retained_numbers):
    checks = []
    for number, retained in zip(numbers, retained_numbers):
        row = cross3_hist_row(record, number)
        args = row.get("arguments") if isinstance(row, dict) else None
        checks.append(
            isinstance(row, dict)
            and row.get("operation") == "sum"
            and isinstance(args, list)
            and len(args) == 2
            and args.count(retained) == 1
            and args[0] != args[1]
        )
    return bool(checks) and all(checks)



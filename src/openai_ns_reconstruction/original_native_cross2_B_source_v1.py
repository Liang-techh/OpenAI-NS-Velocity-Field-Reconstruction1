import json as cross_comp_json

CROSS_COMP_B_Z_RULE = 'B_Z=2*R*R_Z*H+R^2*(Q_Z/L-Q*L_Z/L^2+Q*Q_Z-4*Z*U^2/L^2-4*Z^2*U*U_Z/L^2+4*Z^2*U^2*L_Z/L^3), H=Q/L+Q^2/2-2*Z^2*U^2/L^2'
CROSS_COMP_ACCEPTED_PARENT = list(range(520, 529)) + list(range(531, 536))


def cross_comp_require(condition, message):
    if condition is not True:
        raise AssertionError(message)


def cross_comp_digest(value):
    return cross_comp_hashlib.sha256(cross_comp_json.dumps(
        value, sort_keys=True, separators=(',', ':'), ensure_ascii=True,
        allow_nan=False).encode()).hexdigest()


def cross_comp_emit(callback, events, stage, payload):
    frozen = cross_comp_json.loads(cross_comp_json.dumps(payload, allow_nan=False))
    events.append({'stage': stage, 'payload': frozen})
    if callback is not None:
        callback(stage, frozen)



def _cross3_norm_compact(value):
    return "".join(str(value).split()) if isinstance(value, str) else ""


def _cross3_norm_source_text(value):
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        for key in ("source_text", "text", "body", "source"):
            text = value.get(key)
            if isinstance(text, str):
                return text
    return None


def _cross3_norm_source_value(source_texts, alias):
    if not isinstance(source_texts, dict):
        return None
    for candidate in cross3_norm_source_aliases.get(alias, (alias,)):
        if candidate in source_texts:
            text = _cross3_norm_source_text(source_texts[candidate])
            if isinstance(text, str):
                return text
    return None


def _cross3_norm_sha256(text):
    if not isinstance(text, str):
        return None
    return _cross3_norm_hashlib.sha256(text.encode("utf-8")).hexdigest()


def _cross3_norm_function(tree, name, required_hint=None):
    if not isinstance(tree, _cross3_norm_ast.AST):
        return None
    candidates = [node for node in _cross3_norm_ast.walk(tree)
                  if isinstance(node, (_cross3_norm_ast.FunctionDef,
                                       _cross3_norm_ast.AsyncFunctionDef))
                  and node.name == name]
    if required_hint:
        hint = _cross3_norm_compact(required_hint)
        for candidate in candidates:
            try:
                body = _cross3_norm_compact(_cross3_norm_ast.unparse(candidate))
            except (AttributeError, TypeError):
                body = ""
            if hint in body:
                return candidate
    return candidates[0] if candidates else None



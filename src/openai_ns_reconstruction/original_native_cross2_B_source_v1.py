def _cross3_norm_contract_consistency(source_contracts, source_results):
    details = {}
    source_contracts = source_contracts if isinstance(source_contracts, dict) else {}
    for alias, result in source_results.items():
        reported = None
        for candidate in cross3_norm_source_aliases.get(alias, (alias,)):
            item = source_contracts.get(candidate)
            if isinstance(item, dict):
                reported = item
                break
        details[alias] = {
            "reported": isinstance(reported, dict),
            "reported_sha256": reported.get("sha256") if reported else None,
            "computed_sha256": result.get("sha256"),
            "reported_hash_consistent": (
                reported is None or reported.get("sha256") == result.get("sha256")),
            "reported_AST_parsed": (reported.get("AST_parsed")
                                    if reported else None),
        }
    # Existing V2 contracts are useful context, but the V3 AST checks above
    # remain authoritative and do not accept marker-only evidence.
    return {
        "details": details,
        "passed": all(item["reported_hash_consistent"]
                       for item in details.values()),
        "marker_only_evidence_accepted": False,
    }



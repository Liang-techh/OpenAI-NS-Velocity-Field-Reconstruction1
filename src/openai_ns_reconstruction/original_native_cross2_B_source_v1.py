def _cross3_row_is(record, number, expected):
    row = _cross3_row(record, number)
    return isinstance(row, dict) and all(row.get(key) == value for key, value in expected.items())


def _cross3_substitution_rows(record, numbers, variable, value, allow_zero=False):
    if not isinstance(numbers, list) or not numbers:
        return False
    for number in numbers:
        if allow_zero and number == 0:
            continue
        row = _cross3_row(record, number)
        if not isinstance(row, dict):
            return False
        if not (row.get("operation") == "function_substitution"
                and row.get("variable") == variable
                and row.get("value") == value
                and row.get("Z_independent_substitution") is True):
            return False
    return True


def _cross3_field(mapping, name):
    if not isinstance(mapping, dict):
        return None
    # These are the only serialized endpoint containers used by the pinned
    # C5/C6 snapshots; this is a fixed path list, not a graph search.
    for path in (("correction", name), ("moments", name), ("modified_fields", name),
                 ("fields", name), ("physical", name), (name,)):
        value = _cross3_path(mapping, *path)
        if isinstance(value, list):
            return value
    return None


def _cross3_endpoint_fields(record, endpoint, names, variable, value, allow_zero=False):
    return all(
        _cross3_substitution_rows(record, _cross3_field(endpoint, name), variable, value,
                                   allow_zero=allow_zero)
        for name in names
    )



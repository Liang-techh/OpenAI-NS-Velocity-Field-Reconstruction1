"""Rehydrate checked inputs and compute only the new unchanged pressure segment.

Ancestor constructors load their checked receipts. Their run/checker routines
are never called and their artifacts are never regenerated by this script.
"""
import ast
import inspect
from pathlib import Path
import sys
import textwrap

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'experiments/root_st073'))
import lei_ren_part1_paper_compliant_current_original_n1_unchanged_pressure_prefix as current
import lei_ren_part1_paper_compliant_current_original_n1_unchanged_pressure_prefix_check as check


def build_checked_owner(cls,cache=None):
    """Follow explicit required-owner type guards, preserving shared owners."""
    cache={} if cache is None else cache
    if cls in cache:return cache[cls]
    module=sys.modules[cls.__module__]
    required=[p for p in inspect.signature(cls).parameters.values()
              if p.default is inspect.Parameter.empty
              and p.kind not in (p.VAR_POSITIONAL,p.VAR_KEYWORD)]
    tree=ast.parse(textwrap.dedent(inspect.getsource(cls.__init__)))
    kwargs={}
    for parameter in required:
        match=None
        for node in ast.walk(tree):
            if (isinstance(node,ast.Compare) and isinstance(node.left,ast.Call)
                and isinstance(node.left.func,ast.Name) and node.left.func.id=='type'
                and len(node.left.args)==1 and isinstance(node.left.args[0],ast.Name)
                and node.left.args[0].id==parameter.name and len(node.comparators)==1):
                target=node.comparators[0];path=[]
                while isinstance(target,ast.Attribute):path.append(target.attr);target=target.value
                if isinstance(target,ast.Name):
                    value=vars(module).get(target.id)
                    for attribute in reversed(path):value=getattr(value,attribute)
                    if inspect.isclass(value):match=value;break
        if match is None:
            raise ValueError('Missing checked-owner type: '+cls.__name__+'.'+parameter.name)
        kwargs[parameter.name]=build_checked_owner(match,cache)
    print('LOAD_CHECKED_OWNER',cls.__name__,flush=True)
    owner=cls(**kwargs)
    if hasattr(owner,'acceptance_loaded') and not owner.acceptance_loaded:
        raise ValueError('Checked acceptance was not loaded: '+cls.__name__)
    cache[cls]=owner
    return owner


def main():
    base=build_checked_owner(current.mean.CurrentOriginalN1LeadingMeanEpsilonFactor)
    owner,packets=current.run(base)
    result=check.run(owner,packets)
    public=current.CurrentOriginalN1UnchangedPressurePrefix(base)
    query=public.evaluate('.371')
    assert public.report(query)[current.GATE]
    assert result[current.GATE]
    print('ACCEPTED_UNCHANGED_PRESSURE_PREFIX_PUBLIC',public.acceptance_loaded,flush=True)


if __name__=='__main__':main()

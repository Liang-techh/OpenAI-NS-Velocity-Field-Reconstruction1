"""Directed real-axis C3 logarithmic norm experiment.

This module composes the interval Taylor enclosure from
``uniform_axis_jets`` with the logarithmic derivative recurrence.  It reports
only the one-dimensional axis contribution on ``[-1, 1]``.  In particular,
the result is not a mixed radial/axial norm, a complex-domain bound, a bound
for the frozen ``K`` in the paper, or a full-core certificate.

If ``g = G'`` and ``F = exp(-logC - Lambda G)``, the normalized Taylor
coefficients are generated by

    f[0] = 1,
    f[n+1] = -Lambda * sum(g[k] f[n-k]) / (n+1).

The same recurrence with ``+Lambda`` gives the normalized coefficients for
``1/F``.  Since the interval coefficients are Taylor coefficients, the
actual normalized derivative bound is ``n! |f[n]|``.  The value prefactors
are kept separate and use the analytic enclosure
``-logC - Lambda G_upper <= log(F) <= -logC + Lambda G_upper``.
"""

from __future__ import annotations

import json
from pathlib import Path
import sys
from typing import Any, Iterable

import mpmath as mp
from mpmath.ctx_iv import MPIntervalContext



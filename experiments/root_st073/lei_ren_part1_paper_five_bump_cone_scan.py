"""Nominal interval diagnostics from the internally cached actual Z=.3 source.

Finite sampling of retained P9/W2 jets is not an interval or uniform-Z proof.
The full finite degree-three response is used; quadratic moments retain degree six.
"""
import json
import pickle
from pathlib import Path
from types import SimpleNamespace
import mpmath as mp
from lei_ren_part1_paper_five_moment_reference_background import ReferenceDefectBackground
from lei_ren_part1_paper_axial_dual import AxialDual
from lei_ren_part1_paper_five_bump_map import FiveBumpMomentMap
from lei_ren_part1_paper_five_bump_response import build_response
from lei_ren_part1_paper_five_bump_field import evaluate_correction, join


def nominal(value):
    return value.evaluate() if hasattr(value, 'atoms') else mp.mpf(value)


def metrics(field):
    u=nominal(field['Utheta']); uy=nominal(field['Utheta_y'])
    zy=nominal(field['Uz_y']); F=nominal(field['F'])
    a=1-2*uy/u; b=2*zy/u
    shear_a=-nominal(field['stress']['S_theta'])/F
    shear_b=nominal(field['stress']['S_z'])/F
    shear_error=max(abs(a-shear_a),abs(b-shear_b))
    assert shear_error<mp.mpf('1e-100'), 'Returned shear and cone derivatives disagree'
    D=nominal(field['stress']['I_theta'])/F
    E=nominal(field['stress']['I_z'])/F
    kappa=a+b*b/a; w=E/D
    # Relaxed cone criterion in the kappa <= 2 branch.
    margin=D*(a-b*w)-2*a
    return dict(a=a,b=b,D=D,E=E,kappa=kappa,w=w,
                relaxed_margin=margin,relaxed_margin_over_D=margin/D,
                shear_consistency_error=shear_error,F_positive=F>0,
                D_ge_eight=D>=8,D_positive=D>0,a_positive=a>0,
                kappa_le_two=kappa<=2,relaxed_margin_positive=margin>0)


def run():
    cache=Path(__file__).resolve().parents[2]/'work_paper_cache'/'reference_defect_Z03.pkl'
    # Only the local snapshot generated by reference_background_check is supported.
    with cache.open('rb') as stream: snapshot=pickle.load(stream)
    if snapshot['version']!=1 or snapshot['Z']!='.3':
        raise ValueError('Unsupported local source snapshot')
    precision=snapshot['precision']; data=snapshot['data']
    with mp.workdps(precision):
        z=mp.mpf('.3')
        def source_at(requested):
            if requested!=z: raise ValueError('Snapshot supports Z=.3 only')
            return data
        source=SimpleNamespace(work_precision=precision,Rm=snapshot['Rm'],
                               logPstar=mp.mpf(14),delta=snapshot['delta'],evaluate=source_at)
        reference=ReferenceDefectBackground(source)
        amplitude=AxialDual(data['Am'],data['Am_Z'])
        moment_map=FiveBumpMomentMap(precision=precision,order=96)
        response=build_response(moment_map,amplitude,degree=3)
        terms=response.evaluate_terms([data['d_dual'][i] for i in range(1,6)])
        h=[sum(row[i] for row in terms.values()) for i in range(5)]
        # Include exact support boundaries and nine interior points per bump,
        # alongside the gaps and both reference-interval ends.
        coordinates={mp.mpf(1),mp.exp(1),mp.mpf(2),mp.mpf('1.375'),mp.mpf('1.625')}
        for center in ('1.25','1.5','1.75'):
            coordinates.update(mp.mpf(center)+mp.mpf(j)/200 for j in range(-5,6))
        rows=[]
        for x in sorted(coordinates):
            baseline=reference.evaluate_x(x,z)
            correction=evaluate_correction(moment_map,h,amplitude,source.Rm,z,x,delta=source.delta)
            corrected=join(baseline,correction,delta=source.delta)
            if corrected['stress'] is None: raise RuntimeError(corrected['stress_error'])
            assert corrected['P0']==baseline['P0'] and corrected['P0_Z']==baseline['P0_Z']
            before=metrics(baseline); after=metrics(corrected)
            def encode(mapping):
                return {key:value if isinstance(value,bool) else mp.nstr(value,70)
                        for key,value in mapping.items()}
            rows.append(dict(x=mp.nstr(x,70),baseline=encode(before),corrected=encode(after),
                             P0_preserved=True,source_parts=baseline['source_part_count'],
                             corrected_parts=len(corrected['moment_parts'])))
            print('x='+mp.nstr(x,8)+' margin/D='+mp.nstr(after['relaxed_margin_over_D'],12),flush=True)
        minimum=min(rows,key=lambda row:mp.mpf(row['corrected']['relaxed_margin']))
        report=dict(Z='.3',sample_count=len(rows),precision=precision,
                    pressure_order=9,width_order=2,defect_response_degree=3,
                    moment_degree=6,coefficient_monomial_count=len(terms),
                    nominal_evaluation='retained jet evaluated at pressure=1, width=1',
                    minimum_sample=minimum,rows=rows,
                    all_sampled_relaxed_conditions=all(all(row['corrected'][key] for key in
                        ('a_positive','F_positive','D_positive','kappa_le_two','relaxed_margin_positive')) for row in rows),
                    all_sampled_D_ge_eight=all(row['corrected']['D_ge_eight'] for row in rows),
                    continuous_interval_certified=False,uniform_Z_certified=False,
                    cone_certified=False,source_error_enclosed=False,
                    source_part_hierarchy_preserved=True,
                    nominal_metrics_can_round_tiny_terms=True,
                    functional_closure=False,temporal_recursion=False)
        Path(__file__).with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
        return report


if __name__=='__main__':run()

"""Phase-aligned local profile drift for the global parent and two-patch fields.

The existing localized drift compares profiles at the same angular label.  A
rotating non-axisymmetric pattern can therefore look like scale drift.  This
diagnostic uses the same fixed 7,776-point cylinder and anisotropic pullback,
then fits one global angular phase with a Fourier interpolation through modes
|m| <= 2.  It reports both raw and phase-aligned drift.  This is a sampled
profile diagnostic only; it does not alter any field or establish recursion.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
import time
from pathlib import Path

for _key in ("OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "OMP_NUM_THREADS"):
    os.environ[_key] = "1"

import numpy as np
from scipy.optimize import minimize_scalar

ROOT = Path(__file__).resolve().parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from global_localized_candidate import load as load_parent  # noqa: E402
from global_two_patch_candidate import load as load_two_patch  # noqa: E402
from localized_similarity_drift import cylindrical  # noqa: E402


GRID_PATH = ROOT / "enriched_endpoint_shape_cache.npz"
PARENT_MODULE = ROOT / "global_localized_candidate.py"
TWO_PATCH_MODULE = ROOT / "global_two_patch_candidate.py"
LOCALIZED_REPORT = ROOT / "localized_constrained_tangent.json"
TWO_PATCH_SOURCE = ROOT / "localized_two_patch_constrained.json"
DELTA_K = 1.0e-6
FOURIER_MAX_MODE = 2


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _save(path: Path, report: dict) -> None:
    path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def _load_grid():
    with np.load(GRID_PATH, allow_pickle=False) as loaded:
        points = np.asarray(loaded["points"], dtype=float)
        weights = np.asarray(loaded["weights"], dtype=float)
    if points.shape != (7776, 3) or weights.shape != (7776,):
        raise ValueError(f"Expected fixed cylinder (7776,3)/(7776,), got {points.shape}/{weights.shape}")
    angles = 12
    if len(points) % angles:
        raise ValueError("Point count is not divisible by the angular count")
    block_count = len(points) // angles
    points_blocks = points.reshape(block_count, angles, 3)
    weights_blocks = weights.reshape(block_count, angles)
    radii = np.linalg.norm(points_blocks[:, :, :2], axis=2)
    z = points_blocks[:, :, 2]
    theta = np.arctan2(points_blocks[:, :, 1], points_blocks[:, :, 0])
    # The cache is generated by fixed_cylinder with a single (r,z) node
    # repeated over the twelve angles.  Check that invariant rather than
    # assuming that reshape order is correct.
    consistency = {
        "max_radius_spread": float(np.max(radii - radii[:, :1])),
        "max_z_spread": float(np.max(np.abs(z - z[:, :1]))),
        "max_weight_spread": float(np.max(np.abs(weights_blocks - weights_blocks[:, :1]))),
        "angle_step_error": float(np.max(np.abs(
            np.angle(np.exp(1j * (np.diff(np.unwrap(theta, axis=1), axis=1) - 2.0 * np.pi / angles)))
        ))),
    }
    if max(consistency.values()) > 1.0e-11:
        raise ValueError(f"Fixed-cylinder angular blocks failed consistency checks: {consistency}")
    angle_values = theta[0]
    if np.max(np.abs(np.angle(np.exp(1j * (angle_values - (angle_values[0] + 2.0 * np.pi * np.arange(angles) / angles)))))) > 1.0e-11:
        raise ValueError("Unexpected angular origin/order in fixed-cylinder cache")
    return points, weights, points_blocks, weights_blocks[:, 0], angle_values, consistency


def _cylindrical_blocks(velocity, points_blocks):
    velocity = np.asarray(velocity, dtype=float).reshape(points_blocks.shape)
    flat_points = points_blocks.reshape(-1, 3)
    return cylindrical(velocity.reshape(-1, 3), flat_points).reshape(points_blocks.shape)


def _fourier(values, angles):
    """Return DFT coefficients c_m with f(theta)=sum c_m exp(i*m*theta)."""
    values = np.asarray(values, dtype=float)
    n = values.shape[1]
    modes = np.arange(-n // 2, n // 2, dtype=int)
    coefficients = np.stack([
        np.mean(values * np.exp(-1j * mode * angles)[None, :, None], axis=1)
        for mode in modes
    ], axis=1)
    return modes, coefficients


def _reconstruct(coefficients, modes, angles, max_mode=None):
    coefficients = np.asarray(coefficients)
    modes = np.asarray(modes, dtype=int)
    if max_mode is not None:
        keep = np.abs(modes) <= int(max_mode)
        coefficients = coefficients[:, keep, :]
        modes = modes[keep]
    return np.sum(
        coefficients[:, :, None, :] * np.exp(1j * modes[None, :, None, None] * angles[None, None, :, None]),
        axis=1,
    ).real


def _spectrum(values, angles):
    modes, coefficients = _fourier(values, angles)
    energy = np.sum(np.abs(coefficients) ** 2, axis=(0, 2))
    total = max(float(np.sum(energy)), 1.0e-300)
    return {
        "modes": modes.tolist(),
        "energy_fraction_by_mode": (energy / total).tolist(),
        "energy_fraction_abs_mode_le_2": float(np.sum(energy[np.abs(modes) <= FOURIER_MAX_MODE]) / total),
        "energy_fraction_abs_mode_gt_2": float(np.sum(energy[np.abs(modes) > FOURIER_MAX_MODE]) / total),
        "coefficient_max_abs_mode_gt_2": float(np.max(np.abs(coefficients[:, np.abs(modes) > FOURIER_MAX_MODE, :]))) if np.any(np.abs(modes) > FOURIER_MAX_MODE) else 0.0,
    }


def _weighted_norm(values, weights):
    return float(np.sqrt(np.sum(np.asarray(weights)[:, None, None] * np.asarray(values) ** 2)))


def _phase_fit(reference, endpoint, weights, angles):
    """Fit endpoint(theta+phi) to reference using a |m|<=2 interpolation."""
    ref_modes, ref_coefficients = _fourier(reference, angles)
    end_modes, end_coefficients = _fourier(endpoint, angles)
    if not np.array_equal(ref_modes, end_modes):
        raise ValueError("Reference and endpoint Fourier mode layouts differ")
    keep = np.abs(end_modes) <= FOURIER_MAX_MODE
    modes = end_modes[keep]
    endpoint_coefficients = end_coefficients[:, keep, :]
    reference_coefficients = ref_coefficients[:, keep, :]
    # Since the angular nodes are uniform and each block has one repeated
    # physical weight, Parseval gives the same weighted norm as pointwise
    # reconstruction.  We still evaluate the actual reconstructed arrays so
    # the reported objective is directly comparable to the raw drift.
    def shifted(phi):
        shifted_coefficients = endpoint_coefficients * np.exp(1j * modes[None, :, None] * phi)
        return np.sum(
            shifted_coefficients[:, :, None, :] * np.exp(1j * modes[None, :, None, None] * angles[None, None, :, None]),
            axis=1,
        ).real

    def objective(phi):
        return _weighted_norm(shifted(float(phi)) - reference, weights)

    coarse = np.linspace(-np.pi, np.pi, 4097)
    coarse_values = np.asarray([objective(value) for value in coarse])
    index = int(np.argmin(coarse_values))
    left = float(coarse[max(0, index - 1)])
    right = float(coarse[min(len(coarse) - 1, index + 1)])
    if right <= left:
        phi = float(coarse[index])
        refined = float(coarse_values[index])
        refinement = {"method": "coarse_endpoint", "success": True}
    else:
        result = minimize_scalar(objective, bounds=(left, right), method="bounded", options={"xatol": 1.0e-13})
        phi = float(result.x)
        refined = float(result.fun)
        refinement = {
            "method": "coarse_4097_then_bounded",
            "success": bool(result.success),
            "nfev": int(result.nfev),
            "message": str(result.message),
            "coarse_index": index,
            "coarse_phase": float(coarse[index]),
            "coarse_norm": float(coarse_values[index]),
        }
    aligned = shifted(phi)
    raw = endpoint - reference
    aligned_error = aligned - reference
    return {
        "phase_radians": phi,
        "phase_period": "2*pi",
        "phase_convention": "aligned endpoint is endpoint(theta + phi); positive phi advances endpoint angular profile",
        "raw_L2": _weighted_norm(raw, weights),
        "aligned_L2": _weighted_norm(aligned_error, weights),
        "endpoint_truncated_reconstruction_L2": _weighted_norm(
            _reconstruct(end_coefficients, end_modes, angles, FOURIER_MAX_MODE) - endpoint, weights
        ),
        "reference_truncated_reconstruction_L2": _weighted_norm(
            _reconstruct(ref_coefficients, ref_modes, angles, FOURIER_MAX_MODE) - reference, weights
        ),
        "refinement": refinement,
        "endpoint_spectrum": _spectrum(endpoint, angles),
        "reference_spectrum": _spectrum(reference, angles),
        "aligned_profile": aligned,
    }


def run(output_path=ROOT / "localized_phase_aligned_drift.json"):
    started = time.perf_counter()
    points, weights, points_blocks, block_weights, angles, consistency = _load_grid()
    parent_full, parent_exterior, localized_parent, snapshot_parent, _, _, parent_hashes = load_parent()
    two_patch, localized_two, snapshot_two, two_patch_candidate, two_patch_hashes = load_two_patch()
    if snapshot_parent["inputs"]["mean"]["tau"] != snapshot_two["inputs"]["mean"]["tau"]:
        raise ValueError("Parent and two-patch snapshots use different reference tau")
    tau0 = float(snapshot_parent["inputs"]["mean"]["tau"])
    h = float(localized_parent.inner.h)
    scale = 2.0 ** (-DELTA_K)
    tau1 = tau0 * scale
    mapped_blocks = points_blocks * np.array([scale ** 0.5, scale ** 0.5, scale ** (0.5 - h)])[None, None, :]
    report = {
        "status": "initializing",
        "accepted": False,
        "pde_validated": False,
        "scale_recursion_established": False,
        "scope": (
            "Fixed-cylinder anisotropic profile drift with one global angular phase fit. "
            "Parent is the global_localized_candidate.load return exterior; two_patch is "
            "global_two_patch_candidate.load. Both fields are evaluated directly. This "
            "does not relax PDE, shape, support, or recursion requirements."
        ),
        "sources": {
            "fixed_cylinder_cache": {"path": GRID_PATH.name, "sha256": _sha256(GRID_PATH)},
            "parent_module": {"path": PARENT_MODULE.name, "sha256": _sha256(PARENT_MODULE)},
            "two_patch_module": {"path": TWO_PATCH_MODULE.name, "sha256": _sha256(TWO_PATCH_MODULE)},
            "localized_parent_report": {"path": LOCALIZED_REPORT.name, "sha256": _sha256(LOCALIZED_REPORT)},
            "two_patch_source": {"path": TWO_PATCH_SOURCE.name, "sha256": _sha256(TWO_PATCH_SOURCE)},
        },
        "loader_hashes": {"parent": parent_hashes, "two_patch": two_patch_hashes},
        "grid": {
            "point_count": int(len(points)),
            "angle_count": int(points_blocks.shape[1]),
            "radial_axial_block_count": int(points_blocks.shape[0]),
            "angle_origin_radians": float(angles[0]),
            "angle_spacing_radians": float(2.0 * np.pi / len(angles)),
            "weight_sum": float(np.sum(weights)),
            "angular_block_consistency": consistency,
            "weights_repeated_across_angles": bool(np.max(np.abs(weights.reshape(-1, len(angles)) - block_weights[:, None])) <= 1.0e-15),
            "ordering": "z block, radial panel/node block, then theta=0.31+2*pi*j/12 contiguous",
        },
        "inputs": {
            "reference_tau": tau0,
            "endpoint_tau": tau1,
            "delta_k": DELTA_K,
            "scale": scale,
            "h": h,
            "spatial_map": [scale ** 0.5, scale ** 0.5, scale ** (0.5 - h)],
            "velocity_pullback": [scale ** 0.5, scale ** (0.5 + h), scale ** (0.5 + h)],
            "fourier_interpolation_max_abs_mode": FOURIER_MAX_MODE,
        },
        "fields": {},
    }
    _save(Path(output_path), report)
    print(json.dumps({"stage": "sources_loaded", "point_count": len(points), "angles": len(angles)}), flush=True)

    for name, field in (("parent", parent_exterior), ("two_patch", two_patch)):
        print(json.dumps({"stage": "field_replay_started", "field": name}), flush=True)
        reference_velocity = field.fields(points, tau0)[0]
        endpoint_velocity = field.fields(mapped_blocks.reshape(-1, 3), tau1)[0]
        reference = _cylindrical_blocks(reference_velocity, points_blocks)
        endpoint = _cylindrical_blocks(endpoint_velocity, mapped_blocks)
        reference *= np.array([1.0, 1.0, 1.0])[None, None, :]
        endpoint *= np.array([scale ** 0.5, scale ** (0.5 + h), scale ** (0.5 + h)])[None, None, :]
        fit = _phase_fit(reference, endpoint, block_weights, angles)
        raw_norm = float(fit["raw_L2"])
        aligned_norm = float(fit["aligned_L2"])
        reference_norm = _weighted_norm(reference, block_weights)
        fit.pop("aligned_profile")
        fit.update({
            "reference_profile_L2": reference_norm,
            "raw_relative_profile_L2": raw_norm / max(reference_norm, 1.0e-300),
            "aligned_relative_profile_L2": aligned_norm / max(reference_norm, 1.0e-300),
            "raw_drift_per_abs_log_scale": raw_norm / max(reference_norm, 1.0e-300) / abs(np.log(scale)),
            "aligned_drift_per_abs_log_scale": aligned_norm / max(reference_norm, 1.0e-300) / abs(np.log(scale)),
            "relative_reduction_from_phase_alignment": 1.0 - aligned_norm / max(raw_norm, 1.0e-300),
        })
        report["fields"][name] = fit
        report["status"] = f"{name}_complete"
        _save(Path(output_path), report)
        print(json.dumps({"stage": "field_complete", "field": name,
                          "raw_relative": fit["raw_relative_profile_L2"],
                          "aligned_relative": fit["aligned_relative_profile_L2"],
                          "phase": fit["phase_radians"]}), flush=True)

    report["status"] = "completed"
    report["elapsed_seconds"] = float(time.perf_counter() - started)
    _save(Path(output_path), report)
    print(json.dumps({"stage": "completed", "elapsed_seconds": report["elapsed_seconds"],
                      "fields": {name: {"phase": value["phase_radians"],
                                         "raw": value["raw_relative_profile_L2"],
                                         "aligned": value["aligned_relative_profile_L2"]}
                                 for name, value in report["fields"].items()}}), flush=True)
    return report


if __name__ == "__main__":
    run()
